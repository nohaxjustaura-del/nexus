async function addPrograms() {
  console.log(`Adding ${programs.length} programs...\\n`)
  let added = 0, skipped = 0

  for (const program of programs) {
    try {
      const existing = await prisma.investor.findUnique({
        where: { email: program.email }
      })
      if (existing) {
        skipped++
        continue
      }

      const allInvestors = await prisma.investor.findMany({
        select: { id: true, firmName: true }
      })
      
      if (allInvestors.find(inv => inv.firmName.toLowerCase() === program.firmName.toLowerCase())) {
        skipped++
        continue
      }

      await prisma.investor.create({ data: program })
      console.log(`✅ ${program.firmName}`)
      added++
    } catch (error) {
      console.log(`❌ ${program.firmName}`)
    }
  }

  const total = await prisma.investor.count()
  console.log(`\\n📊 ✅ ${added} | ⏭️  ${skipped} | 📈 Total: ${total} | 🎯 Need: ${1000 - total}\\n`)
  await prisma.$disconnect()
}


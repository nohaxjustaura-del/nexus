// University directory for validation and onboarding datalist suggestions.
// US entries use one canonical name per institution (abbreviations live in ALIASES).

function normalizeKey(input: string): string {
  return input
    .toLowerCase()
    .replace(/[.,’'`]/g, '')
    .replace(/[\u2013\u2014]/g, '-') // en/em dash → hyphen for stable keys
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/-/g, ' ')
}

/** Dedupe by normalized key; stable sort for datalist browsing. */
function uniqueSortedUniversities(names: readonly string[]): string[] {
  const seen = new Set<string>()
  const out: string[] = []
  for (const name of names) {
    const key = normalizeKey(name)
    if (!key || seen.has(key)) continue
    seen.add(key)
    out.push(name)
  }
  return out.sort((a, b) => a.localeCompare(b, 'en', { sensitivity: 'base' }))
}


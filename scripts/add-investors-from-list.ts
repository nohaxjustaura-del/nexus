async function main() {
  console.log('📊 Adding investors from provided list...\n')
  
  // Get existing investors
  const existingInvestors = await prisma.investor.findMany({
    select: {
      email: true,
      firmName: true,
    },
  })
  
  const existingEmails = new Set(existingInvestors.map(i => i.email.toLowerCase()))
  const existingFirmNames = new Set(existingInvestors.map(i => i.firmName.toLowerCase()))
  
  console.log(`Found ${existingInvestors.length} existing investors in database\n`)
  
  // Filter out duplicates
  const newInvestors = investorsToAdd.filter(investor => {
    const emailExists = existingEmails.has(investor.email.toLowerCase())
    const nameExists = existingFirmNames.has(investor.firmName.toLowerCase())
    
    if (emailExists || nameExists) {
      console.log(`⏭️  Skipping duplicate: ${investor.firmName} (${investor.email})`)
      return false
    }
    return true
  })
  
  console.log(`\n✅ Found ${newInvestors.length} new investors to add (out of ${investorsToAdd.length} total)\n`)
  
  if (newInvestors.length === 0) {
    console.log('✨ All investors already exist in database!')
    return
  }
  
  console.log('📝 New investors:')
  newInvestors.forEach((inv, i) => {
    console.log(`${i + 1}. ${inv.firmName} - ${inv.email}`)
  })
  
  // Add to database
  console.log('\n💾 Adding investors to database...\n')
  let added = 0
  let errors = 0
  
  for (const investor of newInvestors) {
    try {
      await prisma.investor.create({
        data: {
          email: investor.email,
          name: investor.name,
          firmName: investor.firmName,
          verified: investor.verified,
          stages: JSON.stringify(investor.stages),
          checkMin: investor.checkMin,
          checkMax: investor.checkMax,
          sectors: JSON.stringify(investor.sectors),
          geoFocus: JSON.stringify(investor.geoFocus),
          leadFollow: investor.leadFollow,
          fundType: investor.fundType,
          fundSize: investor.fundSize,
          applicationUrl: investor.applicationUrl,
          websiteUrl: investor.websiteUrl,
          thesis: investor.thesis,
          valueAddTags: JSON.stringify(investor.valueAddTags),
          ethicsTags: JSON.stringify([]),
          personalityType: investor.personalityType,
          decisionSpeed: investor.decisionSpeed,
        },
      })
      added++
      console.log(`✅ Added: ${investor.firmName}`)
    } catch (error: any) {
      errors++
      console.error(`❌ Error adding ${investor.firmName}:`, error.message)
    }
  }
  
  console.log(`\n✨ Done! Added ${added} investors, ${errors} errors`)
}


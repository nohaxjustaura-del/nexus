// Parse investment range string to min/max in thousands
function parseInvestmentRange(range: string): { min: number; max: number } {
  // Remove $ and K/M suffixes, handle ranges
  const clean = range.replace(/\$/g, '').trim()
  
  if (clean.includes('–') || clean.includes('-')) {
    const parts = clean.split(/[–-]/).map(p => p.trim())
    const min = parseValue(parts[0])
    const max = parseValue(parts[1] || parts[0])
    return { min, max }
  }
  
  const value = parseValue(clean)
  return { min: value, max: value }
}

function parseValue(str: string): number {
  const num = parseFloat(str.replace(/[^0-9.]/g, ''))
  if (str.toLowerCase().includes('m')) {
    return num * 1000 // Convert millions to thousands
  }
  return num
}

// Parse stages from text
function parseStages(stageText: string): string[] {
  const stages: string[] = []
  const lower = stageText.toLowerCase()
  
  if (lower.includes('pre-seed') || lower.includes('pre seed')) stages.push('Pre-Seed')
  if (lower.includes('seed')) stages.push('Seed')
  if (lower.includes('series a')) stages.push('Series A')
  if (lower.includes('series b')) stages.push('Series B')
  if (lower.includes('series c')) stages.push('Series C')
  if (lower.includes('early')) stages.push('Early')
  if (lower.includes('idea')) stages.push('Idea')
  
  return stages.length > 0 ? stages : ['Seed'] // Default to Seed if none found
}

// Parse sectors from text
function parseSectors(sectorText: string): string[] {
  const sectors: string[] = []
  const lower = sectorText.toLowerCase()
  
  // Common sector mappings
  const sectorMap: { [key: string]: string } = {
    'saas': 'SaaS',
    'b2b saas': 'B2B SaaS',
    'marketplaces': 'Marketplaces',
    'fintech': 'Fintech',
    'logistics': 'Logistics',
    'data': 'Data',
    'consumer': 'Consumer',
    'frontier tech': 'Frontier Tech',
    'consumer & enterprise software': 'Consumer Software',
    'consumer internet': 'Consumer Internet',
    'developer tools': 'Developer Tools',
    'retail tech': 'Retail Tech',
    'consumer brands': 'Consumer Brands',
    'supply chain': 'Supply Chain',
    'commerce infra': 'Commerce Infrastructure',
    'cybersecurity': 'Cybersecurity',
    'data science': 'Data Science',
    'national security tech': 'National Security Tech',
    'deep tech': 'Deep Tech',
    'ai/ml': 'AI/ML',
    'robotics': 'Robotics',
    'climate': 'Climate Tech',
    'space': 'Space',
    'health': 'Health',
    'healthtech': 'Healthtech',
    'insurtech': 'Insurtech',
    'media': 'Media',
    'connectivity': 'Connectivity',
    'sports': 'Sports',
    'future of work': 'Future of Work',
    'adtech': 'AdTech',
    'hr': 'HR',
    'sustainability': 'Sustainability',
    'impact': 'Impact',
    'govtech': 'GovTech',
    'all sectors': 'All Sectors',
  }
  
  // Split by comma and check each
  const parts = sectorText.split(',').map(p => p.trim())
  for (const part of parts) {
    const lowerPart = part.toLowerCase()
    for (const [key, value] of Object.entries(sectorMap)) {
      if (lowerPart.includes(key)) {
        if (!sectors.includes(value)) {
          sectors.push(value)
        }
      }
    }
  }
  
  // If no sectors found, try to extract from original text
  if (sectors.length === 0) {
    const allSectors = sectorText.split(',').map(s => s.trim()).filter(s => s.length > 0)
    sectors.push(...allSectors.slice(0, 5)) // Limit to 5
  }
  
  return sectors.length > 0 ? sectors : ['Tech'] // Default
}

// Parse lead/follow status
function parseLeadFollow(statusText: string): string {
  const lower = statusText.toLowerCase()
  if (lower.includes('can lead') || lower.includes('leads')) return 'lead'
  if (lower.includes('co-invest') || lower.includes('co invests') || lower.includes("doesn't take board seats")) return 'follow'
  if (lower.includes('either')) return 'either'
  return 'either' // Default
}

// Parse fund type
function parseFundType(typeText: string): string {
  const lower = typeText.toLowerCase()
  if (lower.includes('vc fund')) return 'institutional'
  if (lower.includes('accelerator')) return 'accelerator'
  if (lower.includes('micro-vc') || lower.includes('micro vc')) return 'micro-VC'
  if (lower.includes('angel')) return 'angel'
  if (lower.includes('syndicate') || lower.includes('angel network')) return 'angel'
  if (lower.includes('corporate')) return 'CVC'
  if (lower.includes('studio') || lower.includes('company builder')) return 'studio'
  if (lower.includes('fellowship') || lower.includes('grant')) return 'fellowship'
  return 'institutional' // Default
}

